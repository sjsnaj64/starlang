# 三、语句 → 源码
# ═══════════════════════════════════════════════════════════
class 打印机:
    def __init__(self, 注释):
        self.注释 = 注释          # {行号: 文字}
        # ★ 花括号模式：正在打印匿名函数的体。
        #   花括号里【不能用缩进块】—— 词法器在花括号内不发 INDENT/DEDENT，
        #   所以这里每个块都得用 { } 写。
        self.花括号里 = False

    def 行尾注释(self, s):
        """这条语句原来那行有没有注释？有就带出来"""
        行 = starlang.语句行表.get(id(s))
        if 行 and 行 in self.注释:
            return "  " + self.注释[行]
        return ""

    def 程序(self, 语句们):
        行们 = []
        for i, s in enumerate(语句们):
            # 函数/宏前面空一行，一大段代码里才分得清哪是哪
            if i > 0 and s[0] in ("funcdef", "macrodef"):
                行们.append("")
            self.块(s, 0, 行们)
        return "\n".join(行们) + "\n"

    def 块(self, s, 层, 行们):
        """打印一条语句（可能展开成多行）"""
        缩 = 缩进宽 * 层
        k = s[0]
        尾 = self.行尾注释(s)

        if k == "print":
            行们.append(缩 + "打印 " + 式(s[1]) + 尾)

        elif k == "assign":
            行们.append(缩 + 安全名(s[1]) + " = " + 式(s[2]) + 尾)

        elif k == "opassign":
            行们.append(缩 + 安全名(s[1]) + " " + s[2] + "= "
                       + 式(s[3]) + 尾)

        elif k == "setindex":
            行们.append(缩 + 式(s[1]) + "[" + 式(s[2]) + "] = " + 式(s[3]) + 尾)

        elif k == "setindexop":
            行们.append(缩 + 式(s[1]) + "[" + 式(s[2]) + "] " + s[3] + "= "
                       + 式(s[4]) + 尾)

        elif k == "expr":
            行们.append(缩 + 式(s[1]) + 尾)

        elif k == "labeled":
            内 = s[2]
            if 内[0] in ("while", "for") and not self.花括号里:
                # ★ 循环的标号长在【条件 / 迭代表达式后面】：
                #       只要 真 @外面
                #       遍历 甲 于 表 @搜索
                #   不能偷懒贴到「最后一行」——那会跑到 body 最后一句的尾上，
                #   标号就挂错了地方（`检查跳出` 找不到它，直接报「一个标号都没写」）。
                if 内[0] == "while":
                    行们.append(缩 + "只要 " + 式(内[1]) + "  @" + s[1] + 尾)
                    self.语句块(内[2], 层 + 1, 行们)
                else:
                    行们.append(缩 + "遍历 " + 安全名(内[1]) + " 于 "
                               + 式(内[2]) + "  @" + s[1] + 尾)
                    self.语句块(内[3], 层 + 1, 行们)
            else:
                # 普通语句（打印/赋值/如果/函数定义…）的标号就贴在它自己那行尾，
                #   这些语句只会打印出一行，所以 行们[-1] 正好是它。
                self.块(内, 层, 行们)
                # ★ 必须用 `@名字` 不能用 `#@名字`：
                #   `#@` 在词法上是【注释】，解析器根本看不到它 ——
                #   而「跳出 这个名字」要靠它找到靶子。
                行们[-1] = 行们[-1] + "  @" + s[1]

        elif k == "block":
            for x in s[1]:
                self.块(x, 层, 行们)

        elif k == "if":
            if self.花括号里:
                # ★ 花括号模式（在匿名函数体里）：每个块都用 { } 写，
                #   因为词法器在花括号内不发 INDENT/DEDENT，缩进块不成立。
                行们.append(缩 + "如果 " + 式(s[1]) + " {")
                self.语句块(s[2], 层 + 1, 行们)
                行们.append(缩 + "}")
                假 = s[3]
                while 假 is not None:
                    if 假[0] == "if":
                        行们.append(缩 + "否则如果 " + 式(假[1]) + " {")
                        self.语句块(假[2], 层 + 1, 行们)
                        行们.append(缩 + "}")
                        假 = 假[3]
                    else:
                        行们.append(缩 + "否则 {")
                        self.语句块(假, 层 + 1, 行们)
                        行们.append(缩 + "}")
                        假 = None
            else:
                行们.append(缩 + "如果 " + 式(s[1]) + 尾)
                self.语句块(s[2], 层 + 1, 行们)
                if s[3] is not None:
                    if s[3][0] == "if":
                        # 否则如果：把「如果」换成「否则如果」
                        临时 = []
                        self.块(s[3], 层, 临时)
                        临时[0] = 缩 + "否则" + 临时[0].lstrip()
                        行们.extend(临时)
                    else:
                        行们.append(缩 + "否则")
                        self.语句块(s[3], 层 + 1, 行们)

        elif k == "while":
            if self.花括号里:
                行们.append(缩 + "只要 " + 式(s[1]) + " {")
                self.语句块(s[2], 层 + 1, 行们)
                行们.append(缩 + "}")
            else:
                行们.append(缩 + "只要 " + 式(s[1]) + 尾)
                self.语句块(s[2], 层 + 1, 行们)

        elif k == "for":
            if self.花括号里:
                行们.append(缩 + "遍历 " + 安全名(s[1]) + " 于 "
                           + 式(s[2]) + " {")
                self.语句块(s[3], 层 + 1, 行们)
                行们.append(缩 + "}")
            else:
                行们.append(缩 + "遍历 " + 安全名(s[1]) + " 于 "
                           + 式(s[2]) + 尾)
                self.语句块(s[3], 层 + 1, 行们)

        elif k == "funcdef":
            默认们 = s[4] if len(s) > 4 else None
            if not isinstance(默认们, list):
                # ★ 兵不厌诈：万一上游给了 None 或别的，就当「没默认值」处理，
                #   别让一个字段缺失把整个工具搞崩。
                默认们 = [None] * len(s[2])
            件 = []
            for i, p in enumerate(s[2]):
                件.append(安全名(p) if 默认们[i] is None
                          else 安全名(p) + " = " + 式(默认们[i]))
            形参 = ", ".join(件)
            if self.花括号里:
                行们.append(缩 + "定义 " + 安全名(s[1]) + "(" + 形参 + ") {")
                self.语句块(s[3], 层 + 1, 行们)
                行们.append(缩 + "}")
            else:
                行们.append(缩 + "定义 " + 安全名(s[1]) + "(" + 形参 + ")" + 尾)
                self.语句块(s[3], 层 + 1, 行们)

        elif k == "return":
            if s[1] is None:
                行们.append(缩 + "返回" + 尾)
            else:
                行们.append(缩 + "返回 " + 式(s[1]) + 尾)

        elif k == "break":
            标签 = s[1] if len(s) > 1 else None
            行们.append(缩 + "跳出" + (" " + 标签 if 标签 else "") + 尾)

        elif k == "continue":
            行们.append(缩 + "继续" + 尾)

        elif k == "try":
            if self.花括号里:
                行们.append(缩 + "尝试 {")
                self.语句块(s[1], 层 + 1, 行们)
                行们.append(缩 + "} 出错 " + s[2] + " {")
                self.语句块(s[3], 层 + 1, 行们)
                行们.append(缩 + "}")
            else:
                行们.append(缩 + "尝试" + 尾)
                self.语句块(s[1], 层 + 1, 行们)
                行们.append(缩 + "出错 " + s[2])
                self.语句块(s[3], 层 + 1, 行们)

        elif k == "register":
            行们.append(缩 + "注册 " + s[1] + " " + 安全名(s[2]) + " "
                       + 安全名(s[3]) + 尾)

        elif k == "unregister":
            行们.append(缩 + "拔掉 " + s[1] + " " + 安全名(s[2]) + " "
                       + 安全名(s[3]) + 尾)

        elif k == "macrodef":
            形参 = ", ".join(安全名(p) for p in s[2])
            行们.append(缩 + "宏 " + 安全名(s[1]) + "(" + 形参 + ")" + 尾)
            self.语句块(s[3], 层 + 1, 行们)

        elif k == "macro":
            # 走不到这儿 —— 展开所有宏() 已经把宏吃掉了。
            # 留着这条是为了「万一」，总不能因为一句话让整个工具崩掉。
            行们.append(缩 + "（没展开的宏 " + s[1] + "）" + 尾)

        elif k == "insert":
            # ★ 走到这儿说明织入没把它吃掉。那也照打，至少不丢东西。
            行们.append(缩 + "（未织入的插入指令）" + 尾)

        else:
            行们.append(缩 + "（认不出的语句 " + repr(k) + "）" + 尾)

    def 语句块(self, 块, 层, 行们):
        """打印一个块的语句们。★ 空的也至少给个占位，不然缩进结构会瞎"""
        语句们 = 块[1] if 是表(块) and 块[0] == "block" else []
        if not 语句们:
            行们.append(缩进宽 * 层 + "占位 = 0    # （原本这里是空的）")
            return
        for s in 语句们:
            self.块(s, 层, 行们)


