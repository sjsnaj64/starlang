# 五、驱动
# ═══════════════════════════════════════════════════════════
def 展开源码(源码, 基准目录=None):
    """返回 (展开后的源码, 织入报告)"""
    starlang.语句行表.clear()
    starlang.当前行[0] = 0
    starlang.宏定义表.clear()

    # ★ 跟解释器一样：先把「载入 "别的.star"」拼进来，再收集注释。
    #   顺序很重要 —— 注释是按行号记的，拼完之后行号才是对的。
    if "载入" in 源码:
        源码 = starlang.展开载入(源码, 基准目录)

    # ★ Step 23：引入 "math" 这类行也得先吃掉（换成空行，行号不动）。
    #   漏了这一步，词法器会把「引入」当成一个普通名字，直接语法错。
    #
    # ★★ 但要【先把原文抄下来】：副本里必须留着这些行，
    #   不然副本跑起来 math_sqrt 全都不认识（验证展开.py 当场就能抓到）。
    引入行们 = []
    if "引入" in 源码:
        for 行 in 源码.replace("\r\n", "\n").split("\n"):
            if starlang.引入行式.match(行):
                引入行们.append(行.rstrip())
        源码 = starlang.展开引入(源码)

    注释 = 收集注释(源码)

    tokens = Lexer(源码).tokenize()
    语句们 = Parser(tokens).parse_program()

    报告 = 织入(语句们)          # ★ 第一步：把「插入」搬进函数体
    语句们 = 展开所有宏(语句们)   # ★ 第二步：把宏原地展开

    打印器 = 打印机(注释)
    正文 = 打印器.程序(语句们)

    头 = (
        "# ============================================================\n"
        "# 这是 展开.py 生成的【只读副本】\n"
        "#\n"
        "# 它做的事：把所有「插入 xxx { … }」搬到对应函数体里，然后打印成源码。\n"
        "# 所以这个文件里的函数就是它们【最终真正会跑的样子】。\n"
        "#\n"
        "# ⚠️ 别拿这个文件当原稿：\n"
        "#    · 里面已经没有插入指令了，再展开一次也没东西可展开\n"
        "#    · 运算符空格/缩进/字符串引号都被规范化过了\n"
        "#    · 独占一行的注释如果上面没有语句了，可能丢掉\n"
        "# ============================================================\n"
    )
    if 报告:
        头 += "#\n# 搬进去的东西：\n"
        for 条 in 报告:
            头 += "#   · " + 条 + "\n"
        头 += "#\n"

    # ★ 引入 行放回副本最前面（它是预处理指令，位置不影响语义）
    前言块 = ""
    if 引入行们:
        前言块 = "\n".join(引入行们) + "\n\n"

    return 头 + "\n" + 前言块 + 正文, 报告


def 跑文件(路径, 输出=None, 直接打=False):
    源码 = io.open(路径, encoding="utf-8-sig").read()
    结果, 报告 = 展开源码(源码, os.path.dirname(os.path.abspath(路径)))

    if 直接打:
        print(结果)
        return None

    if 输出 is None:
        基, 扩 = os.path.splitext(路径)
        输出 = 基 + ".展开" + (扩 or ".star")

    io.open(输出, "w", encoding="utf-8", newline="\n").write(结果)
    print("已生成 " + 输出)
    if 报告:
        print("  搬进去了 %d 处：" % len(报告))
        for 条 in 报告:
            print("    · " + 条)
    else:
        print("  （这个文件里没有插入指令，只是重新排版了一遍）")
    return 输出


def main():
    参数 = sys.argv[1:]
    if not 参数 or 参数[0].startswith("--"):
        print(__doc__)
        return

    路径 = 参数[0]
    输出 = None
    if "--out" in 参数:
        i = 参数.index("--out")
        if i + 1 < len(参数):
            输出 = 参数[i + 1]

    try:
        跑文件(路径, 输出=输出, 直接打=("--print" in 参数))
    except Exception as e:
        print("  ! " + starlang.最终文案(e))


if __name__ == "__main__":
    main()
