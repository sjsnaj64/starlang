# -*- coding: utf-8 -*-
r"""展开.py —— 把「插入」的内容搬回函数体里，生成一份好读的副本

    python 展开.py demo5.star              生成 demo5.展开.star
    python 展开.py demo5.star --out x.star 指定输出文件
    python 展开.py demo5.star --print      直接打到屏幕上

为什么需要它：
    「插入」这东西写的时候爽 —— 不用改原函数那几行，散着写更清楚。
    但读的时候就难受了 —— 一个函数到底会做什么，得把散在各处的插入全翻出来拼一遍。

    这个工具干的是：**织入 → 再打印回源码**。
    生成的文件可以拿去读、拿去对照，但不能直接改回去（见下面的「诚实的说明」）。

它怎么做的：
    ① 跟解释器走同一条流水线：切词 → 建树
    ② 调 starlang.织入() —— 就是解释器跑之前那一步，AST 里插入已经合并好了
    ③ 把 AST 重新打印成源码（缩进风格，不用大括号）

诚实的说明：
    · **注释会尽量保留**（按每条语句原来的行号去查），但独占一行的注释
      如果上面没有语句了（比如文件末尾的注释），就会丢。
    · 输出是**规范化**过的：运算符周围统一空格、缩进统一 4 格、字符串统一双引号。
      所以它不是原文的备份，而是「语义等价的一份新写法」。
    · 已经是织入后的结果了 —— **别再对这个副本跑一次展开**，里面已经没有插入指令。
"""
import io
import os
import sys

import starlang
from starlang import Lexer, Parser, 织入

缩进宽 = "    "

# ═══════════════════════════════════════════════════════════
# 一、先扫一遍原文，把注释收起来（词法器会把它们吃掉，不留下痕迹）
# ═══════════════════════════════════════════════════════════
def 收集注释(源码):
    """返回 {行号: 注释文字}。

    ★ 不能简单用 `#.*`：字符串里的井号（"里面有 # 号"）不是注释。
      所以要跟着引号走一遍。
    """
    注释 = {}
    行 = 1
    i = 0
    n = len(源码)
    行首 = True              # 这一行还没出现过非空白字符？
    while i < n:
        ch = 源码[i]

        if ch == "\n":
            行 += 1
            行首 = True
            i += 1
            continue

        if ch in " \t\r\ufeff":
            i += 1
            continue

        if ch == "#":
            # ★ #@名字 是【标号】不是注释 —— 漏了这句，`打印 x  #@底价`
            #   会被当成「行尾注释 #@底价」，然后打印器再加一遍标号，变成两遍。
            if i + 1 < n and 源码[i + 1] == "@":
                while i < n and 源码[i] != "\n":
                    i += 1
                continue
            起 = i
            while i < n and 源码[i] != "\n":
                i += 1
            注释[行] = 源码[起:i].rstrip()
            行首 = False
            continue

        if ch in ("\"", "'"):
            引号 = ch
            i += 1
            while i < n:
                if 源码[i] == "\\":
                    i += 2
                    continue
                if 源码[i] == 引号:
                    i += 1
                    break
                if 源码[i] == "\n":
                    break
                i += 1
            行首 = False
            continue

        行首 = False
        i += 1

    return 注释


