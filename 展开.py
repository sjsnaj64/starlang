# 二、表达式 → 源码
# ═══════════════════════════════════════════════════════════
# 优先级表：数字越大越「粘得紧」。打印时子表达式优先级比爸爸低就加括号。
优先 = {
    "或": 1, "且": 2,
    "==": 3, "!=": 3, "<": 3, ">": 3, "<=": 3, ">=": 3,
    "+": 4, "-": 4,
    "*": 5, "/": 5, "%": 5,
    "非": 6, "负": 6,
    "**": 7,
    "后缀": 8,
}


def 是表(x):
    return isinstance(x, (tuple, list))


def 安全名(名):
    """★ 宏卫生化造出来的名字长这样：和#1。

    AST 里它是个合法名字，但【源码里写不出来】—— `#` 在星语里是注释符，
    `和#1 = 0` 会被切成「和」+ 注释「1 = 0」。所以打印时要换个写法。

    换成 _宏 是因为用户不会自己起 `和_宏1` 这种名字，撞不上。
    """
    if isinstance(名, str) and "#" in 名:
        return 名.replace("#", "_宏")
    return 名


def 式(n, 父优先=0):
    """把表达式节点打印成源码。父优先 用来决定要不要加括号。"""
    k = n[0]

    if k == "num":
        v = n[1]
        if isinstance(v, float) and v.is_integer() and "." not in repr(v):
            return str(int(v))
        return repr(v) if isinstance(v, float) else str(v)

    if k == "str":
        s = str(n[1])
        s = (s.replace("\\", "\\\\").replace("\"", "\\\"")
             .replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r"))
        return "\"" + s + "\""

    if k == "bool":
        return "真" if n[1] else "假"

    if k == "null":
        return "空"

    if k == "ternary":
        # 三元式优先级最低，被嵌进别的表达式里就得加括号
        结果 = ("如果 " + 式(n[1]) + " 则 " + 式(n[2])
                + " 否则 " + 式(n[3]))
        return "(" + 结果 + ")" if 父优先 else 结果

    if k == "lambda":
        # ★ 打印成 匿名(x) { … } —— 花括号里缩进无所谓（词法器在花括号内
        #   不做缩进处理），所以这里固定用一层缩进就够了。
        #   体里的话得用 打印机 打，所以在这儿现场造个临时的（注释表空着）。
        默认们 = n[3] if len(n) > 3 else [None] * len(n[1])
        件 = []
        for i, p in enumerate(n[1]):
            件.append(安全名(p) if 默认们[i] is None
                      else 安全名(p) + " = " + 式(默认们[i]))
        参 = ", ".join(件)
        临时 = 打印机({})
        临时.花括号里 = True      # ★ 体里的块全用 { } 写
        体行们 = []
        for 句 in n[2][1]:
            临时.块(句, 1, 体行们)
        行们 = ["匿名(" + 参 + ") {"]
        行们.extend(体行们)
        行们.append("}")
        return "\n".join(行们)

    if k == "var":
        return 安全名(n[1])

    if k == "list":
        项 = [式(x) for x in n[1]]
        if not 项:
            return "[]"
        return "[" + ", ".join(项) + "]"

    if k == "dict":
        对 = [式(a) + ": " + 式(b) for a, b in n[1]]
        if not 对:
            return "[:]"
        return "[" + ", ".join(对) + "]"

    if k == "index":
        return 式(n[1], 优先["后缀"]) + "[" + 式(n[2]) + "]"

    if k == "attr":
        # ★ Step 26：模块.名字 —— 原样打回 `模块.名字` 的样子
        return 式(n[1], 优先["后缀"]) + "." + n[2]

    if k == "call":
        实 = ", ".join(式(a) for a in n[2])
        return 式(n[1], 优先["后缀"]) + "(" + 实 + ")"

    # ---- 逻辑：且 / 或 / 非 ----
    if k in ("且", "或"):
        我 = 优先[k]
        左 = 式(n[1], 我)
        右 = 式(n[2], 我 + 1)          # 右边高一级 → 右结合时不多打括号
        结果 = 左 + " " + k + " " + 右
        return "(" + 结果 + ")" if 我 < 父优先 else 结果

    if k == "非":
        结果 = "非 " + 式(n[1], 优先["非"])
        return "(" + 结果 + ")" if 优先["非"] < 父优先 else 结果

    # ---- 一元 ----
    if len(n) == 2:
        结果 = k + 式(n[1], 优先["负"])
        return "(" + 结果 + ")" if 优先["负"] < 父优先 else 结果

    # ---- 二元 ----
    我 = 优先.get(k, 3)
    左 = 式(n[1], 我)
    右 = 式(n[2], 我 + 1)              # 右高一级：a - b - c 打成 a - b - c
    结果 = 左 + " " + k + " " + 右
    return "(" + 结果 + ")" if 我 < 父优先 else 结果


