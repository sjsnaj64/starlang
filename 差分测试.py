r"""差分测试.py —— 随机生成程序，喂给三个实现，看输出对不对得上

    python 差分测试.py                 默认随机 200 个
    python 差分测试.py --个数 1000
    python 差分测试.py --种子 42        种子固定 = 同批「假随机」可复现
    python 差分测试.py --保留           失败的程序存到 _失败/ 里

什么叫「差分测试」：
    同一个程序，三个实现分别跑，比输出。
        ① starlang.py     树遍历解释器
        ② starlangc.py    编译成 Python
        ③ starlangvm.py   字节码虚拟机
    只要有一条输出不一样，就说明至少有一个实现错了 —— 而且**不用人写测试用例**。

★ 最难的不是「随机」，是「随机出来的东西必须能跑完」：
    · 变量没定义 → 崩
    · 除以 0     → 崩
    · 下标越界   → 崩
    · 类型不搭（字符串减数字）→ 崩
    · 死循环     → 跑不完
   崩了就等于什么都没测到，所以生成器必须一边生成一边记事：
   **手上有哪些变量、各是什么类型、列表多长、字典有哪些键、循环几圈**。
"""
