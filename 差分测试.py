# 二、把全局状态洗干净（三个实现共用一堆模块级表）
# ═══════════════════════════════════════════════════════════
def 重置():
    starlang.宏定义表.clear()
    starlang.钩子表.clear()
    starlang.已声明宏.clear()
    starlang.语句行表.clear()
    starlang.当前行[0] = 0
    starlang._gensym[0] = 0
    starlang._宏深度[0] = 0
    starlang._钩子栈.clear()


def 抓输出(函数):
    """把一个实现跑一遍，返回它打印的东西（报错也算输出）"""
    缓冲 = io.StringIO()
    try:
        with contextlib.redirect_stdout(缓冲):
            函数()
    except SystemExit:
        pass
    except Exception as e:
        return 缓冲.getvalue() + "\n《抛异常》" + str(e)
    finally:
        重置()
    return 缓冲.getvalue()


def 跑三方(源码):
    重置()
    A = 抓输出(lambda: starlang.run(源码, echo=True))

    重置()
    def _编译():
        产物, 报告 = starlangc.编译源码(源码)
        环境 = {"__name__": "__星语__"}
        try:
            exec(compile(产物, "<差分>", "exec"), 环境)
        except Exception as e:
            # ★ 必须走产物自己的转换器 —— 跟 starlangc.跑文件() 一模一样。
            #   直接让原始异常冒出去，量出来的就是一条谁都没处理过的英文/原文，
            #   跟另外两边对不上。（差分测试自己踩过这个坑）
            转 = 环境.get("_星语错误文本")
            raise RuntimeError(转(e) if 转 else str(e)) from None
    B = 抓输出(_编译)

    重置()
    C = 抓输出(lambda: starlangvm.跑(源码))

    return A, B, C


# ═══════════════════════════════════════════════════════════
# 三、洗掉「驱动自己的装饰行」，只留程序真正的输出
# ═══════════════════════════════════════════════════════════
装饰 = [
    re.compile(r"^──.*$"),
    re.compile(r"^\s*· "),
    re.compile(r"^\s*插入指令"),
]


def 净(文本):
    行们 = []
    for 行 in 文本.replace("\r\n", "\n").split("\n"):
        if not 行.strip() or any(p.match(行) for p in 装饰):
            continue
        # 行号是每个实现自己算的，位置不同很正常；只比「谁出了什么错」
        行们.append(re.sub(r"第 \d+ 行", "第 ? 行", 行.rstrip()))
    return 行们


