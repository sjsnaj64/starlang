# ═══════════════════════════════════════════════════════════
# 一、生成器
# ═══════════════════════════════════════════════════════════
# 类型就这么几种，够测出实现了：
数, 文, 真假, 表, 典 = "数", "文", "真假", "表", "典"

比较符 = ["<", ">", "<=", ">="]
算符 = ["+", "-", "*"]


class 生成器:
    def __init__(self, 随机数, 最多深度=3):
        self.r = 随机数
        self.最多深度 = 最多深度
        self.变量 = []          # [(名字, 类型)]
        self.函数 = []          # [(名字, [参数类型], 返回类型)]
        self.计数 = 0

    # ---------- 名字 ----------
    def 新名(self, 前缀="x"):
        self.计数 += 1
        return 前缀 + str(self.计数)

    def 同类型变量(self, 类型):
        return [n for n, t in self.变量 if t == 类型]

    # ---------- 表达式 ----------
    def 式(self, 类型, 深度=0):
        """造一个【确定是这种类型】的表达式，返回源码字符串"""
        # 深度到顶了就只出原子，不然会指数爆炸
        if 深度 >= self.最多深度:
            return self.原子(类型)

        choices = ["原子"]
        候选 = self.同类型变量(类型)
        if 候选:
            choices += ["变量", "变量"]        # 变量出现得多一点
        if 类型 == 数:
            choices += ["算术", "算术", "取余", "长度", "取负"]
        elif 类型 == 真假:
            choices += ["比较", "逻辑", "非", "包含"]
        elif 类型 == 文:
            choices += ["拼接", "换文本", "去空白", "取段", "字符拼回"]
        elif 类型 == 表:
            choices += ["再造表", "字符们", "按行分", "下标"]
        elif 类型 == 典:
            choices += ["再造典", "典取键"]

        函数们 = [f for f in self.函数 if f[2] == 类型]
        if 函数们:
            choices.append("调函数")

        做法 = self.r.choice(choices)

        if 做法 == "原子":
            return self.原子(类型)
        if 做法 == "变量":
            return self.r.choice(候选)

        if 做法 == "算术":
            a = self.式(数, 深度 + 1)
            b = self.式(数, 深度 + 1)
            return "(" + a + " " + self.r.choice(算符) + " " + b + ")"

        if 做法 == "取余":
            a = self.式(数, 深度 + 1)
            b = self.式(数, 深度 + 1)
            # ★ 取余的除数必须非 0。加个绝对值再 +1，算出来铁定 > 0
            return "(" + a + " % (" + b + " * " + b + " + 1))"

        if 做法 == "取负":
            return "(-" + self.式(数, 深度 + 1) + ")"

        if 做法 == "长度":
            目标 = self.r.choice([表, 文])
            return "长度(" + self.式(目标, 深度 + 1) + ")"

        if 做法 == "比较":
            运 = self.r.choice(比较符)
            if self.r.random() < 0.5:
                return "(" + self.式(数, 深度 + 1) + " " + 运 + " " \
                    + self.式(数, 深度 + 1) + ")"
            return "(" + self.式(文, 深度 + 1) + " " + 运 + " " \
                + self.式(文, 深度 + 1) + ")"

        if 做法 == "逻辑":
            运 = self.r.choice(["且", "或"])
            return "(" + self.式(真假, 深度 + 1) + " " + 运 + " " \
                + self.式(真假, 深度 + 1) + ")"

        if 做法 == "非":
            return "(非 " + self.式(真假, 深度 + 1) + ")"

        if 做法 == "包含":
            目标 = self.r.choice([表, 文])
            return "含有(" + self.式(目标, 深度 + 1) + ", " \
                + self.原子(数 if 目标 == 表 else 文) + ")"

        if 做法 == "拼接":
            return "(" + self.式(文, 深度 + 1) + " + " + self.式(文, 深度 + 1) + ")"

        if 做法 == "换文本":
            # ★ 换成() 是「文本替找」要 3 个参数，不是类型转换
            return "换成(" + self.式(文, 深度 + 1) + ", \"星\", \"尘\")"

        if 做法 == "去空白":
            return "去空白(" + self.式(文, 深度 + 1) + ")"

        if 做法 == "取段":
            # 取段(文, 0, 1) 无论长短都不越界（空文也是空文）
            return "取段(" + self.式(文, 深度 + 1) + ", 0, 1)"

        if 做法 == "字符拼回":
            return "排成(字符们(" + self.式(文, 深度 + 1) + "), \"-\")"

        if 做法 == "字符们":
            return "字符们(" + self.式(文, 深度 + 1) + ")"

        if 做法 == "按行分":
            return "按行分(" + self.式(文, 深度 + 1) + ")"

        if 做法 == "再造表":
            几项 = self.r.randint(1, 3)
            项 = [self.式(self.r.choice([数, 文, 真假]), 深度 + 1) for _ in range(几项)]
            return "[" + ", ".join(项) + "]"

        if 做法 == "下标":
            # ★ 只用【字面量】当下标目标：非空是肯定的，键也是现成的。
            #   用变量的话得追它到底是不是空表，漏一个就下标越界崩掉。
            几项 = self.r.randint(1, 3)
            项 = [self.原子(self.r.choice([数, 文])) for _ in range(几项)]
            位置 = self.r.randint(-几项, 几项 - 1)      # 负数下标也测了
            return "[" + ", ".join(项) + "][" + str(位置) + "]"

        if 做法 == "典取键":
            几项 = self.r.randint(1, 2)
            对 = ["\"k" + str(i) + "\": " + self.原子(数) for i in range(几项)]
            键 = "\"k" + str(self.r.randint(0, 几项 - 1)) + "\""
            return "[" + ", ".join(对) + "][" + 键 + "]"

        if 做法 == "再造典":
            几项 = self.r.randint(1, 3)
            对 = ["\"k" + str(i) + "\": " + self.式(self.r.choice([数, 文, 真假]), 深度 + 1)
                 for i in range(几项)]
            return "[" + ", ".join(对) + "]"

        if 做法 == "调函数":
            f = self.r.choice(函数们)
            实 = [self.式(t, 深度 + 1) for t in f[1]]
            return f[0] + "(" + ", ".join(实) + ")"

        return self.原子(类型)

    def 原子(self, 类型):
        if 类型 == 数:
            if self.r.random() < 0.3:
                return str(round(self.r.uniform(-20, 20), 2))
            return str(self.r.randint(-20, 20))
        if 类型 == 文:
            return "\"" + self.r.choice(["星", "尘", "abc", "", "你好", "x y"]) + "\""
        if 类型 == 真假:
            return self.r.choice(["真", "假"])
        if 类型 == 表:
            # ★ 最少 1 项 —— 空表拿去取下标会越界崩掉，那就不叫测试了
            几项 = self.r.randint(1, 3)
            项 = [self.原子(self.r.choice([数, 文])) for _ in range(几项)]
            return "[" + ", ".join(项) + "]"
        if 类型 == 典:
            几项 = self.r.randint(0, 2)
            对 = ["\"k" + str(i) + "\": " + self.原子(self.r.choice([数, 文]))
                 for i in range(几项)]
            return "[" + ", ".join(对) + "]" if 对 else "[:]"
        return "0"

    # ---------- 语句 ----------
    def 程序(self, 语句数=8):
        行们 = []

        # ---- ① 宏：定义要在调用之前（解析时就要认得这个名字）----
        self.有宏 = self.r.random() < 0.4
        if self.有宏:
            行们 += [
                "宏 说两遍(什么)",
                "    打印 什么",
                "    打印 什么",
                "",
                # ★ 宏里再调另一个宏 —— 一层套一层，看展开会不会乱
                "宏 单遍(什么)",
                "    打印 什么",
                "",
                "宏 双遍(什么)",
                "    单遍(什么)",
                "    单遍(什么)",
                "",
                # ★ 块参数里再套一层结构（块被摊平进来，里面还是完整的语句）
                #   注意不能用「重复」当宏名 —— 它是 while 的关键字别名。
                "宏 两遍做(做什么)",
                "    做什么",
                "    做什么",
                "",
            ]

        # ---- ② 闭包：函数里再定义函数，内层改外层变量 ----
        self.有闭包 = self.r.random() < 0.4
        if self.有闭包:
            行们 += [
                "定义 造累加器(起始)",
                "    累计 = 起始",
                "    定义 加(量)",
                "        累计 = 累计 + 量",
                "        返回 累计",
                "    返回 加",
                "",
            ]

        # ---- ②.5 递归：函数自己调自己 ----
        self.有递归 = self.r.random() < 0.4
        if self.有递归:
            行们 += [
                "定义 阶乘(n)",
                "    如果 n <= 1",
                "        返回 1",
                "    返回 n * 阶乘(n - 1)",
                "",
            ]

        # ---- ③ 普通函数（函数体只用参数 + 字面量，不碰外面）----
        for _ in range(self.r.randint(0, 2)):
            名 = self.新名("f")
            参数量 = self.r.randint(0, 2)
            参数们 = [self.新名("p") for _ in range(参数量)]
            参数类型们 = [self.r.choice([数, 文, 真假]) for _ in range(参数量)]
            返回类型 = self.r.choice([数, 文, 真假])

            # 造函数体时临时把「外面的变量」藏起来，免得引用到不存在的名字
            存档 = self.变量
            self.变量 = list(zip(参数们, 参数类型们))
            体 = self.式(返回类型, 2)
            self.变量 = 存档

            行们.append("定义 " + 名 + "(" + ", ".join(参数们) + ")")
            行们.append("    返回 " + 体)
            行们.append("")
            self.函数.append((名, 参数类型们, 返回类型))

        # ---- ④ 主体 ----
        for _ in range(语句数):
            行们.append(self.一句())
        return "\n".join(行们)

    def 一句(self):
        做法 = self.r.choice(
            ["赋值"] * 4 + ["打印"] * 4 + ["如果"] * 2 + ["只要"] * 2
            + ["尝试"] * 2 + ["块里定义"] * 2 + ["闭包"] * 2 + ["用宏"] * 2
            + ["遮蔽"] * 2 + ["递归"] * 2 + ["嵌套尝试"] * 2 + ["宏套宏"] * 2
            + ["循环里出错"] * 2 + ["三层嵌套"] * 2 + ["宏块嵌套"] * 2
            + ["跳出"] * 3 + ["继续"] * 3 + ["尝试里跳出"] * 2 + ["空值"] * 2
            + ["匿名"] * 3 + ["匿名立即调"] * 2 + ["匿名闭包"] * 2
            + ["三元"] * 3 + ["复合赋值"] * 3 + ["文本加加"] * 2
            + ["默认参数"] * 3 + ["默认参数引用"] * 2 + ["参数个数错"] * 2
            + ["遍历"] * 3 + ["遍历跳"] * 2 + ["遍历嵌"] * 2 + ["遍历快照"] * 2)

        # ---- ★ 跳出：提前结束循环 ----
        # 这里最值得测的不是「能不能跳出」，是**跳出能不能穿过中间层**。
        # 解释器用异常传递，一不小心就被 尝试/出错 当成普通错误吃掉；
        # 编译器用 Python 的 break，天生穿得过去。两条实现路子完全不同。
        if 做法 == "跳出":
            计 = self.新名("b")
            上限 = self.r.randint(1, 3)
            值 = self.式(数, 2)
            self.变量.append((计, 数))
            return ("%s = 0\n"
                    "只要 真\n"
                    "    %s = %s + 1\n"
                    "    如果 %s > %d\n"
                    "        跳出\n"
                    "    打印 %s" % (计, 计, 计, 计, 上限, 值))

        # ---- ★ 继续：跳过这一圈剩下的 ----
        # 注意计数器是【先加再看】——不然「继续」会跳过自增，直接死循环。
        if 做法 == "继续":
            计 = self.新名("c")
            上限 = self.r.randint(2, 4)
            值 = self.式(数, 2)
            self.变量.append((计, 数))
            return ("%s = 0\n"
                    "只要 %s < %d\n"
                    "    %s = %s + 1\n"
                    "    如果 %s == 2\n"
                    "        继续\n"
                    "    打印 %s" % (计, 计, 上限, 计, 计, 计, 值))

        # ---- ★ 跳出埋在 尝试/出错 里面 ----
        if 做法 == "尝试里跳出":
            计 = self.新名("t")
            上限 = self.r.randint(2, 4)
            self.变量.append((计, 数))
            return ("%s = 0\n"
                    "只要 %s < 6\n"
                    "    %s = %s + 1\n"
                    "    尝试\n"
                    "        如果 %s == %d\n"
                    "            跳出\n"
                    "        打印 \"在\" + %s\n"
                    "    出错 错\n"
                    "        打印 \"不该到这\"\n"
                    "打印 \"完\" + %s" % (计, 计, 计, 计, 计, 上限, 计, 计))

        # ---- ★ 空值：类型 / 相等 / 当真假用 ----
        if 做法 == "空值":
            名 = self.新名("n")
            # 故意不登记进变量表：空值不能被当别的类型拿去用（那是错的）
            return ("%s = 空\n"
                    "打印 类型(%s)\n"
                    "打印 %s == 空\n"
                    "如果 非 %s\n"
                    "    打印 \"空的当假用\"" % (名, 名, 名, 名))

        # ---- ★ 匿名函数：当场造、当场用 ----
        # 三家实现走的路完全不同：
        #   解释器  → 直接造个 Func，最简单
        #   编译器  → Python 表达式位置不能写 def，得「提升」成具名定义塞到语句前面
        #   虚拟机  → 指令流就地铺开，前面加 JUMP 跳过
        # 三条路能对上才说明真对上了。
        if 做法 == "匿名":
            值 = self.式(数, 2)
            return ("打印 折叠([1, 2, 3], 0, 匿名(a, b) { 返回 a + b })\n"
                    "打印 映射([1, 2], 匿名(x) { 返回 x + %s })\n"
                    "打印 匿名(x) { 返回 x * 2 }" % 值)

        # ---- ★ 造出来立刻调用：匿名(x){…}(实参) ----
        if 做法 == "匿名立即调":
            值 = self.式(数, 2)
            return "打印 匿名(x) { 返回 x + 1 }(%s)" % 值

        # ---- ★ 匿名函数当闭包：返回出去的那个还认得外面的变量 ----
        if 做法 == "匿名闭包":
            形参 = self.r.randint(0, 2)
            数字 = str(self.r.randint(1, 9))
            return ("打印 匿名(a) { 返回 匿名(b) { 返回 a + b } }(%s)(%s)"
                    % (数字, 数字))

        # ---- ★ 三元表达式：能当值用的条件 ----
        # 三家实现又好又是三条路：解释器直接三目，编译器用 Python 的
        # a if c else b，VM 自己搭 JUMP 两段。
        if 做法 == "三元":
            甲 = self.式(数, 2)
            乙 = self.式(数, 2)
            return ("打印 如果 %s > %s 则 \"大\" 否则 \"小\"\n"
                    "打印 如果 %s > 0 则 如果 %s > 0 则 1 否则 2 否则 3\n"
                    "打印 \"结果=\" + 如果 %s == %s 则 1 否则 0"
                    % (甲, 乙, 甲, 乙, 甲, 乙))

        # ---- ★ 复合赋值：x += e ----
        # 危险地方在两个：
        #   ① 回显 —— 赋值不是表达式，不能冒出一个「= 15」
        #   ② 字符串 += 要走拼接而不是加法（解释器共用二元逻辑就自动对）
        if 做法 == "复合赋值":
            名 = self.新名("p")
            self.变量.append((名, 数))
            值 = self.式(数, 2)
            运算 = self.r.choice(["+", "-", "*", "%"])
            return ("%s = 7\n"
                    "%s %s= %s\n"
                    "打印 %s" % (名, 名, 运算, 值, 名))

        if 做法 == "文本加加":
            名 = self.新名("t")
            self.变量.append((名, 文))
            return ("%s = \"a\"\n"
                    "%s += \"b\"\n"
                    "%s += \"c\"\n"
                    "打印 %s" % (名, 名, 名, 名))

        # ---- ★ 默认参数：可传可不传 ----
        # 三个实现的路数差别很大：
        #   解释器 → 调用时发现实参不够，直接在【新环境】里现算
        #   编译器 → 形参默认值给哨兵，进函数体再判哨兵现算
        #             （不能用 Python 的 def f(a=表达式)：那是定义时算一次）
        #   VM     → 调用时统一补哨兵，函数入口处判哨兵现算
        if 做法 == "默认参数":
            值 = self.式(数, 2)
            return ("定义 带默认(甲, 乙 = 5, 丙 = %s)\n"
                    "    返回 甲 + 乙 + 丙\n"
                    "打印 带默认(1)\n"
                    "打印 带默认(1, 2)\n"
                    "打印 带默认(1, 2, 3)\n"
                    "打印 带默认" % 值)

        # ---- ★ 默认值引用前面的参数 ----
        if 做法 == "默认参数引用":
            return ("定义 方(宽, 高 = 宽)\n"
                    "    返回 宽 * 高\n"
                    "打印 方(4)\n"
                    "打印 方(4, 3)")

        # ---- ★ 参数个数不对时三家报的话必须一模一样 ----
        if 做法 == "参数个数错":
            return ("定义 收两个(甲, 乙 = 1)\n"
                    "    返回 甲\n"
                    "尝试\n"
                    "    收两个()\n"
                    "出错 错\n"
                    "    打印 错\n"
                    "尝试\n"
                    "    收两个(1, 2, 3)\n"
                    "出错 错\n"
                    "    打印 错")

        # ---- ★ 遍历循环 ----
        # 三家又是三条路：解释器直接 for，编译器靠 Python 的 for，
        # VM 自己实现了一套运行时迭代栈（ITER_START/ITER_NEXT）。
        if 做法 == "遍历":
            值 = self.式(数, 2)
            return ("和 = 0\n"
                    "遍历 项 于 [1, 2, %s]\n"
                    "    和 += 项\n"
                    "打印 和\n"
                    "遍历 字 于 \"甲乙\"\n"
                    "    打印 字\n"
                    "遍历 键 于 [\"a\": 1]\n"
                    "    打印 键" % 值)

        # ---- ★ 遍历 + 跳出/继续（VM 要记得弹迭代栈）----
        if 做法 == "遍历跳":
            return ("遍历 项 于 [1, 2, 3, 4, 5]\n"
                    "    如果 项 == 2 { 继续 }\n"
                    "    如果 项 == 4 { 跳出 }\n"
                    "    打印 项")

        # ---- ★ 嵌套遍历：考验迭代栈的嵌套 ----
        if 做法 == "遍历嵌":
            return ("遍历 甲 于 [1, 2]\n"
                    "    遍历 乙 于 [10, 20]\n"
                    "        如果 乙 == 20 { 跳出 }\n"
                    "        打印 甲 * 乙")

        # ---- ★ 边遍历边改：必须是快照，不能无限下去 ----
        if 做法 == "遍历快照":
            return ("表 = [1, 2, 3]\n"
                    "遍历 项 于 表\n"
                    "    追加(表, 项)\n"
                    "打印 长度(表)")

        # ---- ★ 循环体里处理错误：每圈都炸一次、每圈都接住 ----
        if 做法 == "循环里出错":
            序 = self.新名("i")
            self.变量.append((序, 数))
            return "\n".join([
                序 + " = 0",
                "只要 " + 序 + " < " + str(self.r.randint(1, 3)),
                "    尝试",
                "        打印 1 / 0",
                "    出错 错",
                "        打印 \"循环里接住：\" + 错",
                "    " + 序 + " = " + 序 + " + 1",
            ])

        # ---- ★ 三层嵌：只要 → 如果 → 尝试 ----
        if 做法 == "三层嵌套":
            序 = self.新名("i")
            self.变量.append((序, 数))
            return "\n".join([
                序 + " = 0",
                "只要 " + 序 + " < " + str(self.r.randint(1, 2)),
                "    如果 真",
                "        尝试",
                "            打印 1 / 0",
                "        出错 错",
                "            打印 \"深处接住\"",
                "    " + 序 + " = " + 序 + " + 1",
            ])

        # ---- ★ 块参数里带着完整结构（如果 / 只要）----
        if 做法 == "宏块嵌套" and getattr(self, "有宏", False):
            内 = self.式(self.r.choice([数, 文]), 2)
            return ("两遍做({\n"
                    "    如果 真\n"
                    "        打印 " + 内 + "\n"
                    "    否则\n"
                    "        打印 0\n"
                    "})")

        # ---- ★ 变量遮蔽：参数跟外面同名，改的应该是参数，外面不能动 ----
        if 做法 == "遮蔽":
            外层 = self.新名("sh")
            函数 = self.新名("fn")
            外值 = self.r.randint(1, 9)
            参数值 = self.r.randint(10, 99)
            self.变量.append((外层, 数))
            return ("\n".join([
                外层 + " = " + str(外值),
                "定义 " + 函数 + "(" + 外层 + ")",
                "    " + 外层 + " = " + 外层 + " + 1",
                "    返回 " + 外层,
                "打印 " + 函数 + "(" + str(参数值) + ")",   # 应该是 参数值+1
                "打印 " + 外层,                       # 应该还是 外值
            ]))

        # ---- ★ 递归：自己调自己 ----
        if 做法 == "递归" and getattr(self, "有递归", False):
            return "打印 阶乘(" + str(self.r.randint(1, 8)) + ")"

        # ---- ★ 尝试里套尝试：内层接住了，外层不该再响 ----
        #      但内层的【错误块】里再炸一次，那就该冒到外层去
        if 做法 == "嵌套尝试":
            return ("\n".join([
                "尝试",
                "    尝试",
                "        打印 1 / 0",
                "    出错 内",
                "        打印 \"内层：\" + 内",
                "        打印 1 / 0",          # ← 错误块里再炸
                "出错 外",
                "    打印 \"外层接住了：\" + 外",
            ]))

        # ---- ★ 宏里调宏：双遍 调 单遍，展开应该摊平成四条打印 ----
        if 做法 == "宏套宏" and getattr(self, "有宏", False):
            return "双遍(" + self.式(self.r.choice([数, 文]), 2) + ")"

        # ---- ★ 块里定义的变量，块外面还能用（星语「块不建新环境」的特性）----
        #   用 如果 真 保证一定执行，不然外面引用到未定义的变量就崩了。
        if 做法 == "块里定义":
            名 = self.新名("b")
            类型 = self.r.choice([数, 文, 真假, 表, 典])
            值 = self.式(类型, 2)
            self.变量.append((名, 类型))
            return ("如果 真\n"
                    "    " + 名 + " = " + 值 + "\n"
                    "    " + "打印 " + 名 + "\n"
                    "打印 " + 名)

        # ---- ★ 闭包：每次调用都记着自己那份「累计」----
        if 做法 == "闭包" and getattr(self, "有闭包", False):
            名 = self.新名("c")
            # ★ 千万【不能】把这个名字登记进 self.变量 —— 造累加器() 返回的是
            #   一个【函数】，不是数。登记成数的话，后面某个表达式一拿它做乘法
            #   就会抛 Python 的 TypeError，而且三个实现报的内部类名还不一样。
            return ("\n".join([
                名 + " = 造累加器(" + str(self.r.randint(-5, 5)) + ")",
                "打印 " + 名 + "(" + str(self.r.randint(1, 5)) + ")",
                "打印 " + 名 + "(" + str(self.r.randint(1, 5)) + ")",
            ]))

        # ---- ★ 宏调用：块参数、表达式参数都试 ----
        if 做法 == "用宏" and getattr(self, "有宏", False):
            if self.r.random() < 0.5:
                实 = self.式(self.r.choice([数, 文]), 2)
            else:
                实 = "{\n    打印 " + self.式(self.r.choice([数, 文]), 2) + "\n}"
            return "说两遍(" + 实 + ")"

        if 做法 == "赋值":
            类型 = self.r.choice([数, 文, 真假, 表, 典])
            名 = self.新名("v")
            值 = self.式(类型, 1)
            self.变量.append((名, 类型))
            return 名 + " = " + 值

        if 做法 == "打印":
            类型 = self.r.choice([数, 文, 真假, 表, 典])
            return "打印 " + self.式(类型, 2)

        if 做法 == "如果":
            条件 = self.式(真假, 2)
            真身 = self.式(self.r.choice([数, 文]), 2)
            假身 = self.式(self.r.choice([数, 文]), 2)
            return ("如果 " + 条件 + "\n"
                    + "    打印 " + 真身 + "\n"
                    + "否则\n"
                    + "    打印 " + 假身)

        if 做法 == "只要":
            # ★ 循环必须能停下来：计数器是字面量、只知道加 1，圈数很小
            圈 = self.r.randint(1, 3)
            序 = self.新名("i")
            累计 = self.新名("s")
            self.变量.append((序, 数))
            行们 = [
                序 + " = 0",
                累计 + " = 0",
                "只要 " + 序 + " < " + str(圈),
                "    " + 累计 + " = " + 累计 + " + " + self.式(数, 2),
            ]
            # —— 一半的机会再加一层嵌套循环 ——
            if self.r.random() < 0.5:
                内圈 = self.新名("j")
                内圈数 = self.r.randint(1, 2)
                行们 += [
                    "    " + 内圈 + " = 0",
                    "    只要 " + 内圈 + " < " + str(内圈数),
                    "        " + 累计 + " = " + 累计 + " + " + self.式(数, 2),
                    "        " + 内圈 + " = " + 内圈 + " + 1",
                ]
            行们.append("    " + 序 + " = " + 序 + " + 1")
            self.变量.append((累计, 数))
            return "\n".join(行们)

        if 做法 == "尝试":
            a = self.式(self.r.choice([数, 文]), 2)
            return ("尝试\n"
                    "    打印 " + a + "\n"
                    "出错 错\n"
                    "    打印 \"抓住 \" + 错")

        return "打印 0"


