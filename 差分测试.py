# 四、主流程
# ═══════════════════════════════════════════════════════════
def main():
    参数 = sys.argv[1:]
    个数 = 200
    种子 = None
    起始 = 0
    if "--个数" in 参数:
        i = 参数.index("--个数")
        if i + 1 < len(参数):
            个数 = int(参数[i + 1])
    if "--种子" in 参数:
        i = 参数.index("--种子")
        if i + 1 < len(参数):
            种子 = int(参数[i + 1])
    if "--起始" in 参数:
        i = 参数.index("--起始")
        if i + 1 < len(参数):
            起始 = int(参数[i + 1])

    print("=" * 66)
    print("  差分测试：%d 个随机程序 × 3 个实现" % 个数)
    print("  解释器 / 编译器 / 虚拟机 —— 输出必须一模一样")
    print("=" * 66)
    print()

    好 = 0
    坏 = []
    for 轮 in range(个数):
        本次种子 = ( 种子 + 起始 + 轮) if 种子 is not None else (起始 + 轮)
        r = random.Random(本次种子)
        # ★ 偶尔把表达式深度调大一点：浅层没出过问题，不代表深层也没问题
        深度 = 5 if r.random() < 0.15 else 3
        源码 = 生成器(r, 最多深度=深度).程序(语句数=r.randint(5, 12))

        A, B, C = 跑三方(源码)
        a, b, c = 净(A), 净(B), 净(C)

        if a == b == c:
            好 += 1
            # 跑得久了中间报一声，免得看着像卡死
            if (轮 + 1) % 500 == 0:
                print("  ... 已跑 %d / %d（全对）" % (轮 + 1, 个数))
                sys.stdout.flush()
            continue

        坏.append((本次种子, 源码, A, B, C, a, b, c))
        print("  ❌ 第 %d 个（种子 %d）三方不一致" % (轮 + 1, 本次种子))
        for 名, 有 in (("编译器", b), ("虚拟机", c)):
            if 有 != a:
                for i in range(max(len(a), len(有))):
                    x = a[i] if i < len(a) else "<没有>"
                    y = 有[i] if i < len(有) else "<没有>"
                    if x != y:
                        print("     %s 第 %d 行不同：" % (名, i + 1))
                        print("       解释器： " + repr(x))
                        print("       %-5s： %s" % (名, repr(y)))
                        break
        print()

    print("─" * 66)
    print("通过 %d / %d" % (好, 个数))

    if 坏 and "--保留" in 参数:
        if not os.path.isdir(失败目录):
            os.makedirs(失败目录)
        for 本次种子, 源码, A, B, C, a, b, c in 坏:
            io.open(os.path.join(失败目录, "种子%d.star" % 本次种子),
                    "w", encoding="utf-8", newline="\n").write(源码)
        print("失败的程序已存到 " + 失败目录)

    if 坏:
        print()
        print("最快的复现方式：")
        print("    python 差分测试.py --种子 %d --个数 1" % 坏[0][0])
        return 1

    print("三个实现在 %d 个随机程序上完全一致 🐾" % 个数)
    return 0


if __name__ == "__main__":
    sys.exit(main())
