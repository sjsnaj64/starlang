# -*- coding: utf-8 -*-
"""验证库.py —— 检查「星语当库用」三个方向是不是真都通

    python 验证库.py

★★ 为什么这个也要单独验？

    「能当库用」这种话最容易自欺：
      ① 跑个 1+2 就说通了 —— 那只是把 run() 换个名字；
      ② 拿个函数调一次就说通了 —— 没验过参数、返回值、错误；
      ③ 忘了验「两个实例会不会互相串味」—— 这种最坑，因为它要跑久才炸。

    所以下面每条都是【断言】。跑不过就是没通。
"""
import starlang

通过 = [0]
失败 = []


def 查(说明, 实际, 期望):
    if 实际 == 期望:
        通过[0] += 1
        print("  ✅ %-40s → %r" % (说明, 实际))
    else:
        print("  ❌ %-40s → %r（期望 %r）" % (说明, 实际, 期望))
        失败.append(说明)


def 查异常(说明, 函数, 类型=RuntimeError):
    try:
        函数()
    except 类型 as e:
        通过[0] += 1
        print("  ✅ %-40s → 抛了 %s" % (说明, type(e).__name__))
        return
    except Exception as e:                      # noqa: BLE001
        print("  ❌ %-40s → 抛的是 %s，不是 %s" % (说明, type(e).__name__,
                                                类型.__name__))
    else:
        print("  ❌ %-40s → 居然没抛异常" % 说明)
    失败.append(说明)


print("═" * 64)
print("  验证：星语当库用")
print("═" * 64)

# ═══ ① 星语算个值给 Python ═══
print("\n① 星语 → Python（值）")
m = starlang.星语()
查("执行 1 + 2", m.执行("1 + 2"), 3)
查("返回值就是 Python 原生 int", type(m.执行("1 + 2")), int)
查("字符串也是原生 str", m.执行('"你好"'), "你好")
查("列表也是原生 list", m.执行("[1, 2, 3]"), [1, 2, 3])
查("字典也是原生 dict", m.执行('["甲": 1]'), {"甲": 1})
查("空程序返回 None", m.执行(""), None)

# ═══ ② 变量来回搬 ═══
print("\n② 变量往返")
m2 = starlang.星语({"单价": 100, "名字": "星语"})
查("带进去的变量星语读得到", m2.执行("单价 * 3"), 300)
m2.执行("总价 = 单价 * 5")
查("星语算完 Python 拿得走", m2.环境.vars["总价"], 500)
查("原来的变量还在", m2.环境.vars["名字"], "星语")
m2.给变量("折扣", 0.8)
查("事后 给变量 也生效", m2.执行("总价 * 折扣"), 400.0)

# ═══ ③ 星语函数给 Python 调 ═══
print("\n③ Python 调星语函数")
m3 = starlang.星语()
m3.执行('''
定义 加税(元, 税率 = 0.06)
    返回 元 * (1 + 税率)
''')
加税 = m3.取("加税")
查("单参数（吃默认值）", round(加税(100), 4), 106.0)
查("双参数", round(加税(100, 0.1), 4), 110.0)
查("函数名带出来了", 加税.__name__, "加税")
查("取不存在的名字给 None", m3.取("根本没有"), None)
查("有() 问得出来", m3.有("加税"), True)
查("有() 对不存在的给 False", m3.有("根本没有"), False)
查异常("参数给多了会报错", lambda: 加税(1, 2, 3))

# 星语函数还能再传回星语（当参数用）
m3.执行('定义 两次(f, x) { 返回 f(f(x)) }')
两次 = m3.取("两次")
查("星语函数传给星语函数", round(两次(加税, 100), 4), 112.36)

# ═══ ④ Python 函数给星语调 ═══
print("\n④ 星语调 Python 函数")
m4 = starlang.星语()
m4.给函数("平方", lambda x: x * x)
m4.给函数("打招呼", lambda 谁: "你好，" + 谁)
查("调 Python 函数", m4.执行("平方(7)"), 49)
查("带回文本", m4.执行('打招呼("世界")'), "你好，世界")
查("Python 函数结果能参与运算", m4.执行("平方(3) + 平方(4)"), 25)
查异常("Python 抛的错会被包成星语错误",
       lambda: m4.执行('平方("不是数字")'))

# ═══ ⑤ 错误体验一致 ═══
print("\n⑤ 错误")
m5 = starlang.星语()
m5.执行('定义 除(甲, 乙) { 返回 甲 / 乙 }')
除 = m5.取("除")
查异常("除零报的是 RuntimeError", lambda: 除(1, 0))
try:
    除(1, 0)
except RuntimeError as e:
    查("错误信息是中文大白话", "数学" in str(e) or "除数" in str(e), True)
    查("错误信息带行号", "行" in str(e), True)

# ═══ ⑥ 实例之间不能串味 ═══
print("\n⑥ 隔离")
a = starlang.星语({"x": 1})
b = starlang.星语({"x": 2})
a.执行("x = x + 10")
查("a 的 x 变了", a.环境.vars["x"], 11)
查("b 的 x 没被带着变", b.环境.vars["x"], 2)
查("a 看不到 b 的变量", a.有("b才有的"), False)

# ═══ ⑦ with 会自动摘名字 ═══
print("\n⑦ with 收尾")
with starlang.星语() as c:
    c.给("临时函数", lambda: 1)
    查("with 里面能调", c.执行("临时函数()"), 1)
    查("with 里面在全局字典里", "临时函数" in starlang.内建函数, True)
查("with 出来后摘干净了", "临时函数" in starlang.内建函数, False)

# ═══ ⑧ 跟「引入 Python 库」能一起用 ═══
print("\n⑧ 引入 + 库模式")
m8 = starlang.星语()
查("库模式里也能 引入", round(m8.执行('引入 "math"\nmath_sqrt(16)'), 4), 4.0)
starlang.撤掉引入()

# ═══ 收尾 ═══
print()
print("─" * 64)
print("通过 %d 项" % 通过[0])
if 失败:
    print("没过 %d 项：" % len(失败))
    for 名 in 失败:
        print("   · " + 名)
    raise SystemExit(1)
print("星语 ⇄ Python 三个方向全通 🐾")
