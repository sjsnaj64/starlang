def main():
    print("=" * 70)
    print("  报错文案预览    （风格 = " + str(报错文案.风格) + "）")
    print("=" * 70)

    命中 = 0
    总数 = 0

    for 说明, 源码 in 样例:
        总数 += 1
        原文 = ""
        try:
            starlang.run(源码, env=None)
            continue                     # 没报错就不看
        except Exception as e:
            原文 = str(e)

        新 = starlang.改写报错(原文)
        if 新 != 原文:
            命中 += 1
            标 = "✅"
        else:
            标 = "  "

        print()
        print(标 + " " + 说明)
        if 新 != 原文:
            print("     原： " + 原文)
            print("     新： " + 新)
        else:
            print("     原： " + 原文 + "   ← 这条还没自定义")

    print()
    print("─" * 70)
    print("改了 %d / %d 条" % (命中, 总数))
    if 命中 == 0:
        print("（风格还是“正经”吧？改 报错文案.py 里的 风格 那一行试试）")


if __name__ == "__main__":
    main()
