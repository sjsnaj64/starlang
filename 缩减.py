def 打印对比(源码):
    A, B, C = D.跑三方(源码)
    a, b, c = D.净(A), D.净(B), D.净(C)
    名们 = (("解释器", a), ("编译器", b), ("虚拟机", c))
    基线 = a
    print("  " + "─" * 58)
    for 名, 行们 in 名们:
        标 = "" if 行们 == 基线 else "   ← 不一样"
        if 行们:
            print("  %-6s %s%s" % (名, 行们[0][:52], 标))
        else:
            print("  %-6s <无输出>%s" % (名, 标))
    for 名, 行们 in 名们[1:]:
        if 行们 == 基线:
            continue
        for i in range(max(len(基线), len(行们))):
            x = 基线[i] if i < len(基线) else "<没有>"
            y = 行们[i] if i < len(行们) else "<没有>"
            if x != y:
                print("  %s 第 %d 行不一样：" % (名, i + 1))
                print("     解释器： %s" % x)
                print("     %s： %s" % (名.ljust(3, "　"), y))
                break


