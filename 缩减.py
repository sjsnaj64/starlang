# 一、判定：这版还是不是「原来那个 bug」
# ═══════════════════════════════════════════════════════════
_缓存 = {}
_尝试 = [0]


def 分歧对(源码):
    """跑三家，返回「谁跟谁不一样」的指纹。三方一致返回 None"""
    if 源码 in _缓存:
        return _缓存[源码]
    _尝试[0] += 1
    A, B, C = D.跑三方(源码)
    a, b, c = D.净(A), D.净(B), D.净(C)
    对 = set()
    if a != b:
        对.add(("解释器", "编译器"))
    if a != c:
        对.add(("解释器", "虚拟机"))
    if b != c:
        对.add(("编译器", "虚拟机"))
    结果 = frozenset(对) if 对 else None
    _缓存[源码] = 结果
    return 结果


# ═══════════════════════════════════════════════════════════
# 二、死循环防护
# ═══════════════════════════════════════════════════════════
# ★ 条件后面那个 `@标号` 不属于条件 —— 必须剥掉。
#   否则 `只要 真 @外层` 会把「外层」当成一个循环变量，
#   然后要求循环体里给它赋值（当然没有），于是判定「不安全」
#   → 整个程序一行都删不动（Step 22 加标号后当场撞上）。
循环头 = re.compile(
    r"^(\s*)(只要|当|循环|重复|loop)\s+(.+?)(?:\s+@[\w\u4e00-\u9fff]+)?\s*$")
赋值句 = re.compile(r"^\s*([\w\u4e00-\u9fff]+)\s*=(?!=)")
名字 = re.compile(r"[\w\u4e00-\u9fff]+")
# ★ 这些词出现在条件里也不是「变量」：
#   把 `只要 真` 当成「依赖变量 真」的话，就会去要求给 `真` 赋值 ——
#   于是所有常量条件循环都被判成死循环风险，缩减器直接罢工。
非变量词 = set(D.starlang.BOOL_WORDS) | set(D.starlang.NULL_WORDS)


def 循环安全(源码):
    """粗略但有效：循环条件里点名的变量，循环体内必须还有人给它赋值

      只要 假 { … }                → 条件里没变量，永远不进门，放行
      只要 x1 < 3 { x1 = x1 + 1 }  → x1 在条件里也在体内，放行
      只要 x1 < 3 { 打印 x1 }      → 删掉了计数器更新，拦下
      只要 真 { … 跳出 … }         → 常量条件的唯一出口就是「跳出」，必须有
      只要 真 { … }                → 删掉了跳出 → 原地死循环，拦下
    """
    行们 = 源码.split("\n")
    单元 = 语句块(行们)
    出口词 = tuple(D.starlang.BREAK_WORDS) + tuple(D.starlang.RETURN_WORDS)

    for k, (起, 止, 缩) in enumerate(单元):
        m = 循环头.match(行们[起])
        if not m:
            continue
        # ★ 去掉布尔/空值字面量：`只要 真` 是常量条件，不是「依赖变量 真」
        条件里的 = set(名字.findall(m.group(3))) - 非变量词

        # 把这个循环体的行收集起来（缩进更深的都算）
        体行们 = []
        for j in range(k + 1, len(单元)):
            if 单元[j][2] <= 缩:        # 出了循环体
                break
            体行们.append(行们[单元[j][0]].strip())

        if not 条件里的:
            # ★ 常量条件（只要 真 / 只要 0）—— 循环不会自己停，
            #   唯一的出口是「跳出」或「返回」。
            #   ★★ 这一条是补丁：最初漏了它，缩减时把「跳出」那行删掉，
            #   候选程序立刻原地死循环，每次尝试都要跑满 50 万圈熔断，
            #   几百次尝试下来 Terminals 直接被挂死（真的踩了）。
            有出口 = any(行 and 行.split()[0] in 出口词 for 行 in 体行们)
            if not 有出口:
                return False
            continue

        体内赋值的 = set()
        for 行 in 体行们:
            a = 赋值句.match(行)
            if not a:
                continue
            名 = a.group(1)
            if isinstance(名, str) is False:
                continue
            右边 = 行.split("=", 1)[1] if "=" in 行 else ""
            # ★ 只认「自引用」赋值（i = i + 1 这种）才算数。
            #   为什么？因为 i = 0 每圈都把条件变量打回原样，
            #   条件永远为真 —— 是标准的死循环写法。
            #   ★★ 这条是补丁：之前只要「有赋值」就放行，结果缩减时把
            #   i = i + 1 简化成 i = 0，候选立刻变成死循环，
            #   三家在「跑多少圈算死循环」上又不一致，缩减器抓着这个
            #   假 bug 不放，缩出来的「最小复现」其实毫无意义（还卡终端）。
            if re.search(r"(?<![\w\u4e00-\u9fff])" + re.escape(名)
                         + r"(?![\w\u4e00-\u9fff])", 右边):
                体内赋值的.add(名)
        if not (条件里的 & 体内赋值的):
            return False
    return True


def 设定熔断(值):
    """把三个实现的死循环熔断都调小。

    ★ 缩减会不停试「这个删掉行不行」，其中难免试出死循环。
      三个实现的熔断丝撑到 50 万圈时，一次尝试就要跑一两秒 ——
      几百次尝试就是几十分钟，看着像卡死（其实就是）。
      调小到几千圈，死循环候选立刻被否掉，速度回到正常。

    ★ 代价：缩减「本来就要跑很多圈」的真实程序时会误判。
      随机生成的测试程序最多 3 圈，不受影响；真遇到就 --熔断 调大。
    """
    for 模 in (D.starlang, D.starlangc, D.starlangvm):
        if hasattr(模, "MAX_LOOP"):
            模.MAX_LOOP = 值
    # 编译器是把圈数写进产物里的，所以改完模块变量还要重新编译才生效
    # —— 每次候选都是现编译的，天然拿到新值。


# ═══════════════════════════════════════════════════════════
# 三、把源码切成「语句单元」
# ═══════════════════════════════════════════════════════════
def 是空或注释(行):
    s = 行.strip()
    return (not s) or s.startswith("#")


def 语句块(行们):
    """返回 [(起, 止, 缩进)]，止是排他的，且会把紧跟的空行一起吃进来

    星语是缩进语法，删语句必须连它整块子语句一起删，不然就是语法错误。
    「一个单元 = 这一行 + 缩进比它深的所有行」正好就是一块。
    """
    单元 = []
    for i, 行 in enumerate(行们):
        if 是空或注释(行):
            continue
        单元.append([i, None, len(行) - len(行.lstrip())])
    for k in range(len(单元)):
        单元[k][1] = 单元[k + 1][0] if k + 1 < len(单元) else len(行们)
    return [(a, b, c) for a, b, c in 单元]


# ═══════════════════════════════════════════════════════════
# 四、三层缩减手法
# ═══════════════════════════════════════════════════════════
def 做判定器(目标):
    """「还坏吗」的判定器：必须还是同一个分歧对，且不能死循环"""
    def 还坏(行们):
        if not 行们:
            return False
        源码 = "\n".join(行们)
        if not 源码.strip():
            return False
        if not 循环安全(源码):        # ★ 先花 0 成本挡住死循环
            return False
        return 分歧对(源码) == 目标
    return 还坏


def 行级缩减(行们, 还坏):
    """第一层：delta debugging —— 一次删一大段，删不动就改小段

    这层不认识语法，纯粹按行切块删。最快把 200 行砍到 20 行。
    删坏了语法？那三家会一致地报同一个语法错 → 分歧对变 None → 自动回退。
    """
    n = 2
    while len(行们) >= 2:
        块 = max(1, (len(行们) + n - 1) // n)
        改 = False
        for i in range(0, len(行们), 块):
            试 = 行们[:i] + 行们[i + 块:]
            if 还坏(试):
                行们 = 试
                改 = True
                n = max(n - 1, 2)
                break
        if not 改:
            if n >= len(行们):
                break
            n = min(n * 2, len(行们))
    return 行们


def 单元级缩减(行们, 还坏):
    """第二层：按「语句单元」删 —— 一次删掉一条完整语句（连同子块）

    行级缩减会留下半截 if / 半截循环，这层负责把残渣收拾干净。
    每次删成功就从头重扫，因为单元下标全变了。
    """
    while True:
        改了 = False
        for 起, 止, _缩 in 语句块(行们):
            试 = 行们[:起] + 行们[止:]
            if 还坏(试):
                行们 = 试
                改了 = True
                break
        if not 改了:
            return 行们


def 候选简化(行):
    """给一行，产出「更简单」的候选版本（由轻度到彻底）"""
    缩进 = 行[:len(行) - len(行.lstrip())]
    体 = 行.strip()
    候选 = []

    数 = re.compile(r"(?<![\w\u4e00-\u9fff])\d+(?![\w\u4e00-\u9fff])")
    串 = re.compile(r'"[^"\n]*"')

    # —— 轻度：把数字和字符串换成最简形式，结构不动 ——
    新 = 数.sub("0", 串.sub('""', 体))
    if 新 != 体:
        候选.append(缩进 + 新)

    # —— 中度：控制流条件换常量（先进门 / 不进门各试一次）——
    m = re.match(r"^(如果|假如|若|要是|否则如果|否则若|elif|elseif|不然如果)"
                 r"\s+(.+)$", 体)
    if m and m.group(2) not in ("真", "假", "true", "false"):
        候选.append(缩进 + m.group(1) + " 假")
        候选.append(缩进 + m.group(1) + " 真")
    m = 循环头.match(行)
    if m and m.group(3) not in ("真", "假", "true", "false"):
        候选.append(缩进 + m.group(2) + " 假")

    # —— 彻底：整句退化成最朴素的形态（名字保留，后面可能还要用）——
    首词 = 体.split()[0] if 体.split() else ""
    if 首词 in D.starlang.PRINT_WORDS:
        候选.append(缩进 + 首词 + " 0")
    if 首词 in D.starlang.RETURN_WORDS:
        候选.append(缩进 + 首词 + " 0")
    a = 赋值句.match(体)
    if a and 体.split("=", 1)[1].strip() != "0":
        候选.append(缩进 + a.group(1) + " = 0")

    去重 = []
    for c in 候选:
        if c != 行 and c not in 去重:
            去重.append(c)
    return 去重


def 简化级缩减(行们, 还坏):
    """第三层：逐行把表达式换简单 —— 这是最后 20 行砍到 5 行的关键"""
    while True:
        改了 = False
        for i in range(len(行们)):
            for 新行 in 候选简化(行们[i]):
                试 = 行们[:i] + [新行] + 行们[i + 1:]
                if 还坏(试):
                    行们 = 试
                    改了 = True
                    break
            if 改了:
                break
        if not 改了:
            return 行们


def 缩减(源码, 目标=None):
    """完整流程。返回 (最小源码, 报告)"""
    if 目标 is None:
        目标 = 分歧对(源码)
        if 目标 is None:
            return 源码, {"说明": "这个程序三方一致，没有 bug 可以缩"}
    还坏 = 做判定器(目标)
    行们 = 源码.replace("\r\n", "\n").split("\n")
    原行数 = len(行们)

    # 三层轮着来，直到一整轮都没法再动
    while True:
        前 = len(行们)
        行们 = 行级缩减(行们, 还坏)
        行们 = 单元级缩减(行们, 还坏)
        行们 = 简化级缩减(行们, 还坏)
        if len(行们) == 前:
            break

    # 收尾：去掉首尾空行
    while 行们 and not 行们[0].strip():
        行们.pop(0)
    while 行们 and not 行们[-1].strip():
        行们.pop()

    return "\n".join(行们), {"原行数": 原行数, "目标": 目标}


