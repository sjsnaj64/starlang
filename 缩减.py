# -*- coding: utf-8 -*-
r"""缩减.py —— 把「三方不一致」的程序，自动缩减成最小可复现片段

    python 缩减.py 种子379.star          缩减一个文件
    python 缩减.py --种子 379            现场用种子生成再缩减
    python 缩减.py xx.star --输出 最小.star
    python 缩减.py --自测                检验缩减器本身灵不灵

★★ 为什么需要这个工具？

    差分测试的 bug 长这样：2500 个随机程序里 1 个不过，那个程序 200 行，
    变量叫 x1 x2 p3 f4，还有一堆宏和闭包。人工翻 20 分钟才知道是哪一行。

    但计算机很擅长做一件笨事：**不停删，删到不能再删为止**。
    只要「删掉之后 bug 还在」就留下这次删除 —— 最后剩下的就是
    「少了这一行 / 这一句，bug 就消失」的最小证据。

    这套法子业界叫 **delta debugging**（Zeller 1999），
    找 GCC/Clang bug 的 Csmith、找 SQLite bug 的 SQLancer 都在用。

★★ 难点不在「删」，在「怎么算同一个 bug」

    缩减过程中不能只看「三方还不一致」—— 因为删着删着可能
    删出【另一个】不一致，那叫 bug 漂移，缩出来的东西跟原来没关系了。

    所以用「分歧对」当指纹：
        原本是  解释器 ≠ 编译器、解释器 ≠ 虚拟机   （解释器孤立）
        缩减后必须还是这么孤立，不能变成 编译器 ≠ 虚拟机。

★★ 还有个坑：缩减会把程序缩成死循环

        只要 x1 < 3
            x1 = x1 + 1        ← 把这行删了，x1 永远小，就地卡死

    解释器没有圈数熔断（虚拟机有），所以一旦删出来工具自己也挂。
    因此每次候选都要先过一遍「循环安全」检查：循环条件里用到的变量，
    循环体里必须还有人给它赋值（除非条件本身就是常量，永远不进门）。
"""
