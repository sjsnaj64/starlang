# 七、自测：验证缩减器本身靠不靠谱
# ═══════════════════════════════════════════════════════════
def 自测():
    """故意造一个假 bug：只要程序里出现「魔数 424242」，就说三方不一致。
    然后看缩减器能不能把 200 行砍到只剩带魔数的那一行。
    """
    print("自测：装一个假 bug —— 含 424242 的候选一律判为「不一致」")
    原跑 = D.跑三方

    def 假跑(源码):
        A, B, C = 原跑(源码)
        if "424242" in 源码:
            return A, B + "\n《抛异常》只有编译器这样说", C
        return A, B, C

    D.跑三方 = 假跑
    try:
        r = random.Random(7)
        源码 = D.生成器(r, 最多深度=3).程序(语句数=10)
        源码 = "打印 1\n" + 源码 + "\n打印 424242\n打印 2"
        行们 = 源码.split("\n")
        行们.insert(len(行们) // 2, "打印 424242")
        源码 = "\n".join(行们)
        print("  输入 %d 行" % len(行们))
        最小, 报告 = 缩减(源码)
        print("  输出 %d 行：" % len(最小.split("\n")))
        print("  " + "─" * 40)
        for 行 in 最小.split("\n"):
            print("    " + 行)
        print("  " + "─" * 40)
        if "424242" in 最小 and len(最小.split("\n")) <= 3:
            print("  ✅ 缩减器正常（剩下的确实都跟 bug 有关）")
            return 0
        print("  ❌ 缩减器有问题：要么把 bug 删没了，要么留了一堆无关代码")
        return 1
    finally:
        D.跑三方 = 原跑


