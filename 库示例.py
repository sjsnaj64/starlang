# -*- coding: utf-8 -*-
"""库示例.py —— Python 当宿主，星语当「规则引擎」

    python 库示例.py

这个方向的价值跟「引入 Python 库」正好互补：
    · 引入 —— 星语借 Python 的能力（算数学、读写 JSON）
    · 这个 —— Python 借星语的表达力（写业务规则不用编译、不用重启）

真实用途长这样：游戏/机器人/表单校验里那些「老在改的小规则」，
丢给星语写，Python 只负责调度。
"""
import starlang


# ═══════════════════════════════════════════════
# ① 星语算个值给 Python
# ═══════════════════════════════════════════════
m = starlang.星语()
print("① 星语算出来的值：", m.执行("(1 + 2) * 3"), type(m.执行("1 + 2")).__name__)

# 带初始变量进去，用同一个「小世界」反复跑
m2 = starlang.星语({"单价": 100})
m2.执行("总价 = 单价 * 3")
print("   带变量进去：单价", m2.环境.vars["单价"], "→ 总价", m2.环境.vars["总价"])


# ═══════════════════════════════════════════════
# ② 星语写的函数，Python 直接调
# ═══════════════════════════════════════════════
m3 = starlang.星语()
m3.执行('''
定义 算折扣(金额, 会员等级)
    如果 会员等级 == "金" 且 金额 > 1000
        返回 金额 * 0.8
    如果 会员等级 == "金"
        返回 金额 * 0.9
    返回 金额
''')

算折扣 = m3.取("算折扣")
print()
print("② Python 调星语函数：")
for 等级 in ("金", "银"):
    for 额 in (800, 2000):
        print("   %s卡 %4d 元 → %.0f 元" % (等级, 额, 算折扣(额, 等级)))

# 星语里定义的列表，Python 拿到就是 list —— 零转换
m3.执行('名单 = ["甲", "乙", "丙"]')
print("   星语的列表拿到 Python：", m3.取("名单"), type(m3.取("名单")).__name__)


# ═══════════════════════════════════════════════
# ③ Python 的函数，星语直接调
# ═══════════════════════════════════════════════
m4 = starlang.星语()
m4.给函数("现在几点", lambda: "下午三点")
m4.给函数("打招呼", lambda 谁: "你好，" + 谁)
m4.给函数("平方", lambda x: x * x)

print()
print("③ 星语调 Python 函数：")
m4.执行('''
打印 "   现在是：" + 现在几点()
打印 "   " + 打招呼("世界")
打印 "   7 的平方 = " + 平方(7)
''')


# ═══════════════════════════════════════════════
# ④ 来回跑：Python 给数据 → 星语算 → Python 用结果
# ═══════════════════════════════════════════════
m5 = starlang.星语({"订单": [
    {"商品": "苹果", "数量": 3, "单价": 5},
    {"商品": "香蕉", "数量": 2, "单价": 8},
]})
m5.执行('''
总价 = 0
明细 = []
遍历 单 于 订单
    小计 = 单["数量"] * 单["单价"]
    总价 += 小计
    追加(明细, 单["商品"] + "×" + 单["数量"] + " = " + 小计)
''')
print()
print("④ 星语算完，Python 拿走结果：")
for 行 in m5.取("明细"):
    print("   " + 行)
print("   总计：%.0f 元" % m5.取("总价"))


# ═══════════════════════════════════════════════
# ⑤ 星语里报错 → Python 那边是普通异常
# ═══════════════════════════════════════════════
m6 = starlang.星语()
m6.执行('定义 除(甲, 乙) { 返回 甲 / 乙 }')
除 = m6.取("除")
print()
print("⑤ 星语的错误在 Python 这边：")
try:
    除(1, 0)
except RuntimeError as e:
    print("   抓到了 RuntimeError：" + str(e))

# 函数名和参数表也能看见（方便写文档 / 做反射）
print("   函数名：", 除.__name__)
print("   参数表：", 除.__doc__)


# ═══════════════════════════════════════════════
# 收尾：with 语句会自动摘掉注册进去的名字
# ═══════════════════════════════════════════════
print()
with starlang.星语() as m7:
    m7.给("翻倍", lambda x: x * 2)
    print("⑥ with 里面：", m7.执行("翻倍(21)"))
print("   with 出来之后，那个名字已经摘掉了：", "翻倍" in starlang.内建函数)
