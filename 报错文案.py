import re

_当前 = 预设.get(风格) or 自定义
规则 = _当前["规则"]
说法 = _当前["说法"]
外套 = _当前["外套"]

_编译好的 = []
for _式, _说 in 规则:
    try:
        _编译好的.append((re.compile(_式), _说))
    except re.error:
        pass          # 正则写错了就当没写，别把程序本身弄崩


def 改写(消息):
    """把一条报错改成你想要的说法。认不出来就原样返回。"""
    for 式, 说 in _编译好的:
        m = 式.search(消息)
        if m:
            try:
                return 外套 + 说.format(*m.groups())
            except (IndexError, KeyError, ValueError):
                return 外套 + 说
    for 片段, 说 in 说法.items():
        if 片段 in 消息:
            return 外套 + 说
    return 外套 + 消息
